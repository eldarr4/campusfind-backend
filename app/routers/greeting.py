def render_page():
    team = "".join(
        f'<article class="member"><h3>{escape(m["name"])}</h3>'
        f'<p class="sid">Student ID: {escape(m["student_id"])}</p><p>{escape(m["built"])}</p></article>'
        for m in TEAM
    )
    endpoints = "".join(
        f'<li><span class="method {m}">{m}</span><span class="path">{escape(p)}</span>'
        f'<span class="desc">{escape(d)}</span></li>'
        for m, p, d in ENDPOINTS
    )
    return (PAGE.replace("__NAME__", escape(PROJECT_NAME))
                .replace("__DESCRIPTION__", escape(PROJECT_DESCRIPTION))
                .replace("__VERSION__", escape(API_VERSION))
                .replace("__TEAM__", team)
                .replace("__ENDPOINTS__", endpoints))


@router.get("/greeting", response_class=HTMLResponse)
def greeting():
    # Starlette sends "Content-Type: text/html; charset=utf-8".
    return HTMLResponse(content=render_page())
